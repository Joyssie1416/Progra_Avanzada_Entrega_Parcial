        print("[*] Iniciando la búsqueda de detalles geográficos (navegación a sub-páginas en paralelo)...")

        direcciones_y_coords = []

        # Usamos ThreadPoolExecutor para hacer las solicitudes de detalle en paralelo (más rápido)
        with ThreadPoolExecutor(max_workers=10) as executor:
            # Mapeamos la función de extracción de detalles a la columna de IDs
            future_to_id = executor.map(extraer_coordenadas_y_direccion, df_base['ID Mapa (Nro Parte)'])

            # Recogemos los resultados
            for result in future_to_id:
                direcciones_y_coords.append(result)

        # Separamos los resultados en un DataFrame de detalles
        df_detalle = pd.DataFrame(direcciones_y_coords, columns=['Dirección Completa', 'Coordenadas (Lat, Lon)'])

        # Combinar el DataFrame base con los detalles
        df_final = pd.concat([df_base.reset_index(drop=True), df_detalle], axis=1)

        print("\n" + "="*70)
        print("✅ EXTRACCIÓN EXITOSA. DATAFRAME COMPLETO GENERADO.")
