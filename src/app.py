# URL base para los detalles de cada incidente, usando el "numparte"
BASE_DETAIL_URL = "https://sgonorte.bomberosperu.gob.pe/24horas/Home/Map?numparte="

def extraer_coordenadas_y_direccion(id_emergencia):
    """
    Intenta extraer la dirección y coordenadas de la página de detalle.
    Utiliza búsqueda por estructura HTML y, como alternativa, por patrón de texto (RegEx).
    """
    url_detalle = BASE_DETAIL_URL + id_emergencia
    headers = {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/91.0.4472.124 Safari/537.36'
    }

    # Mensajes por defecto si no se encuentra la información
    direccion_defecto = "Contenido NO Cargado (JS Requerido)"
    coordenadas_defecto = "N/A"

    try:
        response = requests.get(url_detalle, headers=headers, timeout=10)
        response.raise_for_status()

        # ----------------------------------------------------
        # 1. Intento A: Búsqueda basada en la estructura HTML (más precisa)
        # ----------------------------------------------------
        soup_detalle = BeautifulSoup(response.content, 'html.parser')

        # Buscamos el último <td> con colspan="2", donde está la dirección
        celdas_colspan_2 = soup_detalle.find_all('td', colspan='2')

        if celdas_colspan_2:
            # Seleccionamos el último, que es donde encontraste la dirección
            direccion_celda = celdas_colspan_2[-1]
            texto_completo = direccion_celda.get_text().strip()

            # Limpiar espacios múltiples
            texto_limpio = re.sub(r'\s{2,}', ' ', texto_completo)

            # Patrón para extraer las coordenadas: (-XX.XXXX,-YY.YYYY)
            match_coords = re.search(r'\(([-]?\d+\.\d+),([-]?\d+\.\d+)\)', texto_limpio)

            if match_coords:
                latitud = match_coords.group(1)
                longitud = match_coords.group(2)
                coordenadas = f"{latitud}, {longitud}"

                # Eliminar las coordenadas del texto para dejar solo la dirección limpia
                direccion_limpia = re.sub(r'\s*\(([-]?\d+\.\d+),([-]?\d+\.\d+)\)\s*', ' ', texto_limpio).strip()

                return direccion_limpia, coordenadas
            else:
                # Si el <td> existe pero no tiene el formato de coordenadas, devolvemos el texto encontrado
                return texto_limpio, coordenadas_defecto

        # ----------------------------------------------------
        # 2. Intento B: Búsqueda agresiva de Coordenadas en el texto fuente (Fallback)
        # ----------------------------------------------------

        # Busca el patrón de coordenadas en el texto sin procesar (podría estar en JS oculto)
        match_script_coords = re.search(r'([-]?\d+\.\d+), ?([-]?\d+\.\d+)', response.text)

        if match_script_coords:
            latitud = match_script_coords.group(1)
            longitud = match_script_coords.group(2)
            coordenadas = f"{latitud}, {longitud}"

            # Si se encuentra en el script, la dirección detallada no será visible para 'requests'
            return direccion_defecto, coordenadas

        # Si no se encontró nada en ambos intentos
        return direccion_defecto, coordenadas_defecto

    except requests.exceptions.HTTPError as err:
        # Manejar errores de HTTP (404, 500, etc.)
        return f"Error HTTP ({err.response.status_code})", coordenadas_defecto
    except Exception as e:
        # Manejar otros errores de conexión o parsing
        return f"Error al Conectar/Extraer Detalle: {type(e).__name__}", coordenadas_defecto


def extraer_tabla_emergencias(url):
    """
    Paso 1: Extrae los datos iniciales (ID, Fecha, Tipo) de la tabla principal.
    CORRECCIÓN: La búsqueda de la tabla es más flexible para evitar el error anterior.
    """
    headers = {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/91.0.4472.124 Safari/537.36'
    }

    try:
        response = requests.get(url, headers=headers, timeout=15)
        response.raise_for_status()
    except Exception as e:
        print(f"[❌] ERROR al obtener la página principal: {e}")
        return None

    soup = BeautifulSoup(response.content, 'html.parser')

    # *** CORRECCIÓN CRÍTICA AQUÍ ***
    # Buscamos una tabla que contenga "table-bordered" en su clase (más flexible)
    tabla = soup.find('table', class_=lambda c: c and 'table-bordered' in c.split())

    if not tabla:
        print("[❌] ERROR: No se encontró la tabla de emergencias. (La clase podría haber cambiado)")
        return None

    datos_iniciales = []
    # Busca todas las filas de la tabla principal, excluyendo el encabezado <thead>
    filas = tabla.find('tbody').find_all('tr')

    for fila in filas:
        celdas = fila.find_all(['th', 'td'])

        # Debe tener al menos 5 celdas con datos relevantes (Nro Parte, Fecha/Hora, Tipo)
        if len(celdas) >= 5:
            datos_fila = {}

            # Columna 1: Nro Parte -> ID único (celda[1])
            nro_parte_element = celdas[1].find('span')
            datos_fila['ID Mapa (Nro Parte)'] = nro_parte_element.get_text().strip() if nro_parte_element else "N/A"

            # Columna 2: Fecha y hora (celda[2])
            fecha_hora_element = celdas[2].find('span')
            datos_fila['Fecha y hora'] = fecha_hora_element.get_text().strip() if fecha_hora_element else "N/A"

            # Columna 4: Tipo (celda[4])
            tipo_element = celdas[4].find('span')
            tipo = tipo_element.get_text().strip() if tipo_element else celdas[4].get_text().strip()
            datos_fila['Tipo'] = re.sub(r'\s{2,}', ' ', tipo).strip() # Limpiamos espacios

            datos_iniciales.append(datos_fila)

    return pd.DataFrame(datos_iniciales)


