def verificar_conexion(url):
    """
    Intenta conectar con la URL especificada y verifica el código de estado HTTP.

    Args:
        url (str): La URL de la página web objetivo.

    Returns:
        bool: True si la conexión fue exitosa (código 200), False en caso contrario.
    """
    # Usamos un User-Agent para simular un navegador real.
    headers = {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/91.0.4472.124 Safari/537.36'
    }

    print(f"Intentando conectar con: {url}")
    print("--------------------------------------------------")

    try:
        # Realizamos la petición HTTP GET con un tiempo de espera de 10 segundos
        response = requests.get(url, headers=headers, timeout=10)

        codigo_estado = response.status_code
        print(f"Conexión establecida. Código de estado HTTP: {codigo_estado}")

        if codigo_estado == 200:
            print("¡La conexión fue exitosa! El servidor respondió correctamente.")
            return True
        elif codigo_estado >= 400 and codigo_estado < 500:
            print(f"Error del Cliente ({codigo_estado}). Es posible que la página no exista (404) o que el servidor haya bloqueado la solicitud (403).")
            return False
        elif codigo_estado >= 500:
            print(f"Error del Servidor ({codigo_estado}). El sitio web tiene problemas internos.")
            return False
        else:
            print(f"Código de estado no esperado ({codigo_estado}).")
            return False


    except requests.exceptions.ConnectionError as e:
        print(f"ERROR CRÍTICO DE CONEXIÓN:")
        print(" Asegúrate de que la URL esté escrita correctamente (incluyendo http:// o https://).")
        print(f"    Detalles: {e}")
        return False
    except requests.exceptions.Timeout:
        print(f"ERROR: Tiempo de Espera (Timeout) agotado. El servidor tardó demasiado en responder.")
        return False
    except Exception as e:
        print(f"Ocurrió un error inesperado: {e}")
        return False

